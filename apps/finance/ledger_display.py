"""Current workspace rows, separate from the immutable accounting history.

Never use this projection for balances or exports. Corrections and reversals
remain in reporting.selectors.financial_entries and in every financial total.
"""
import re
from uuid import UUID

from django.db.models import Q

from apps.events.models import RaffleTicket
from apps.reporting.selectors import financial_entries
from .models import Expense, ExpenseStatus, FinancialEntry, FinancialEntryKind


def _reference_id(reference, prefix):
    if not reference.startswith(prefix):
        return None
    try:
        value = UUID(reference[len(prefix):len(prefix) + 36])
    except (ValueError, AttributeError):
        return None
    # Only source references generated by this application are projected.
    expected = prefix + str(value)
    if not reference.startswith(expected):
        return None
    suffix = reference[len(expected):]
    patterns = {
        'EXPENSE-': r'(?:|-(?:PAY|REOPEN)-\d+|-VOID|-[a-f0-9]{20}-(?:REVERSAL|CORRECTION))',
        'RAFFLE-': r'-(?:SALE|VOID|EDIT-[a-f0-9]{16})',
    }
    return value if prefix in patterns and re.fullmatch(patterns[prefix], suffix) else None


def operational_financial_entries(event, start=None, end=None):
    """Show only the currently effective manual records in the workspace.

    Lookup the latest source posting before applying the requested date range:
    an older posting must not reappear because its replacement is in a new month.
    Real order receipts, fees and refunds retain their full cash representation.
    """
    rows = financial_entries(event, start, end).exclude(
        Q(sponsor_receipt__reversed_at__isnull=False) |
        Q(sponsor_reversal__isnull=False)
    )

    manual_rows = list(FinancialEntry.objects.filter(
        event=event, movement__isnull=False,
    ).order_by('created_at', 'pk').values(
        'pk', 'movement_id', 'movement__archived_at', 'source_reference'))
    known_manual_rows = []
    latest_manual_post = {}
    latest_manual_revision = {}
    for row in manual_rows:
        prefix = f"MANUAL-{row['movement_id']}-"
        if not row['source_reference'].startswith(prefix):
            continue
        suffix = row['source_reference'][len(prefix):].rsplit('-', 1)
        if len(suffix) != 2 or not suffix[0].isdigit() or suffix[1] not in ('POST', 'REVERSAL'):
            continue
        known_manual_rows.append(row)
        if suffix[1] == 'POST' and int(suffix[0]) >= latest_manual_revision.get(row['movement_id'], -1):
            latest_manual_post[row['movement_id']] = row['pk']
            latest_manual_revision[row['movement_id']] = int(suffix[0])
    hidden = [row['pk'] for row in known_manual_rows if row['movement__archived_at'] or
              row['pk'] != latest_manual_post.get(row['movement_id'])]

    # Expenses and paper tickets predate typed ledger foreign keys. Resolve their
    # stable references in batches; do not infer cancellation from descriptions.
    expense_rows = list(FinancialEntry.objects.filter(
        event=event, kind=FinancialEntryKind.DESPESA,
        source_reference__startswith='EXPENSE-',
    ).order_by('created_at', 'pk').values('pk', 'source_reference', 'amount_cents_signed'))
    expense_origins = {row['pk']: _reference_id(row['source_reference'], 'EXPENSE-') for row in expense_rows}
    expense_states = dict(Expense.objects.filter(
        event=event, pk__in={value for value in expense_origins.values() if value},
    ).values_list('pk', 'status'))
    latest_expense_debit = {}
    for row in expense_rows:
        origin = expense_origins[row['pk']]
        if origin in expense_states and row['amount_cents_signed'] < 0:
            latest_expense_debit[origin] = row['pk']
    hidden.extend(row['pk'] for row in expense_rows
              if expense_origins[row['pk']] in expense_states and (
                  expense_states[expense_origins[row['pk']]] != ExpenseStatus.PAID or
                  latest_expense_debit.get(expense_origins[row['pk']]) != row['pk']))

    ticket_rows = list(FinancialEntry.objects.filter(
        event=event, source_reference__startswith='RAFFLE-',
        kind__in=[FinancialEntryKind.RECEITA_SORTEIO, FinancialEntryKind.ESTORNO_SORTEIO],
    ).values_list('pk', 'source_reference'))
    ticket_origins = {pk: _reference_id(reference, 'RAFFLE-') for pk, reference in ticket_rows}
    void_tickets = set(RaffleTicket.objects.filter(
        raffle__event=event, source='PAPER', state='VOID',
        pk__in={value for value in ticket_origins.values() if value},
    ).values_list('pk', flat=True))
    hidden.extend(pk for pk, origin in ticket_origins.items() if origin in void_tickets)
    return rows.exclude(pk__in=hidden)


def mark_ledger_history(entries, event):
    """Label superseded rows without allowing destructive actions on old versions."""
    rows = list(entries)
    current = set(operational_financial_entries(event).filter(
        pk__in=[row.pk for row in rows],
    ).values_list('pk', flat=True))
    for row in rows:
        row.ledger_history_only = row.pk not in current
        row.ledger_status_label = 'Excluída, revertida ou substituída' if row.ledger_history_only else 'Em vigor'
        if row.ledger_history_only:
            row.remove_url = ''
            if row.action_label.startswith('Editar'):
                row.action_label = 'Consultar cadastro atual'
    return rows
